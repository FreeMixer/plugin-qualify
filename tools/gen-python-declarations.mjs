/*
 * gen-python-declarations.mjs — `tools/_declarations.py`, generated from the package's ONE
 * declarations module, `src/qualify-declarations.ts` (`docs/design/specs/2026-09-25-plugin-qualify.md` §4;
 * first written for the 2026-09-17 declare-derive audit, F8, as harness/catalog-python-declarations-gen.mjs).
 * `benchmark.py`'s `DEFAULT_BLOCK`, `DEFAULT_RATES` and timeouts are these facts under its own names.
 *
 * `benchmark.py` cannot import a TS module — that scan's own comment already names the mirror as
 * "known" — so this is the `omx_contract_limits.h` shape in its cheapest form: a file emitted on
 * demand, committed, and checked byte-identical rather than hand-typed twice.
 *
 * Usage:
 *   node tools/gen-python-declarations.mjs --check   # exit 1 if the committed file is stale
 *   node tools/gen-python-declarations.mjs --write   # (re)write the committed file
 *   node tools/gen-python-declarations.mjs --emit-stdout   # print it (R-094's cross-language arm)
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(PKG, 'tools/_declarations.py');

const D = await import(join(PKG, 'dist/qualify-declarations.js'));

/** The declarations the Python tools read, in the order the file states them. */
const PY_NAMES = [
  'COST_REFERENCE_RATE',
  'QUANTUM_FRAMES',
  'MEASURE_BASE_RATE',
  'OPERATIONAL_RATE_FLOOR',
  'QUALIFY_RATES',
  'QUALIFY_QUANTA',
  'PLUGIN_TIMEOUT_S',
  'BOOT_TIMEOUT_S',
  'COST_TIMEOUT_S',
];

const py = (v) => (Array.isArray(v) ? `(${v.join(', ')})` : String(v));

export function declarationsFile() {
  return (
    `# SPDX-License-Identifier: GPL-3.0-or-later\n` +
    `# Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>\n` +
    `#\n` +
    `# GENERATED by tools/gen-python-declarations.mjs — do not hand-edit.\n` +
    `#\n` +
    `# Source: src/qualify-declarations.ts. The Python tools cannot import a TS module, so this file\n` +
    `# stands in for that import: regenerated and checked byte-identical instead of a second,\n` +
    `# hand-typed copy of the figures (2026-09-17 declare-derive audit, F8).\n` +
    `#\n` +
    `# Regenerate: node tools/gen-python-declarations.mjs --write\n` +
    `# Verify:     node tools/gen-python-declarations.mjs --check\n` +
    `\n` +
    PY_NAMES.map((n) => `${n} = ${py(D[n])}\n`).join('')
  );
}

function main() {
  const mode = process.argv[2];
  const content = declarationsFile();
  if (mode === '--emit-stdout') {
    process.stdout.write(content);
    return;
  }
  if (mode === '--check') {
    let onDisk;
    try {
      onDisk = readFileSync(OUT, 'utf8');
    } catch (err) {
      console.error(`gen-python-declarations: cannot read ${OUT}: ${err.message}`);
      process.exit(1);
    }
    if (onDisk !== content) {
      console.error(`gen-python-declarations: ${OUT} is stale — run with --write`);
      process.exit(1);
    }
    console.log('gen-python-declarations: up to date');
    return;
  }
  if (mode === '--write') {
    writeFileSync(OUT, content);
    console.log(`gen-python-declarations: wrote ${OUT}`);
    return;
  }
  console.error('usage: node tools/gen-python-declarations.mjs --check|--write|--emit-stdout');
  process.exit(2);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
