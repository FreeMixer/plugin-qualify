/*
 * gen-hosting-codes.mjs — `src/hosting-codes.generated.ts`, omx-clap-core's hosting tables flattened
 * into one `key: code` map, as plain data.
 *
 * The codes are omx-clap-core's (tools/clap-core-tsdir.mjs finds its TypeScript modules). They reach
 * `HOSTING_CODE` as a generated module rather than a read at import, so every module a public subpath
 * reaches stays free of `node:` imports and bundles for a browser (#134). The file is committed and
 * checked identical, as `tools/_declarations.py` is; `pnpm build` regenerates it whenever omx-clap-core's
 * modules are found, and keeps the committed one where they are not.
 *
 * Usage:
 *   node tools/gen-hosting-codes.mjs --check   # exit 1 if the committed file is stale, 2 if omx-clap-core is absent
 *   node tools/gen-hosting-codes.mjs --write   # (re)write the committed file; omx-clap-core required
 *   node tools/gen-hosting-codes.mjs --build   # --write when omx-clap-core is found, else keep the committed file
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { clapCoreTsDirCandidates, findClapCoreTsDir, flattenHostingTables, loadHostingTables } from './clap-core-tsdir.mjs';

const PKG = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = join(PKG, 'src/hosting-codes.generated.ts');

/** The generated module's text for a flattened `key: code` map. */
export function hostingCodesFile(flat) {
  const lines = Object.entries(flat).map(([key, code]) => `  ${JSON.stringify(key)}: ${JSON.stringify(code)},\n`);
  return (
    `// SPDX-License-Identifier: GPL-3.0-or-later\n` +
    `// Copyright (C) 2026 Pau Aliagas <linuxnow@gmail.com>\n` +
    `//\n` +
    `// GENERATED by tools/gen-hosting-codes.mjs from omx-clap-core's hosting tables — do not hand-edit.\n` +
    `//\n` +
    `// Regenerate: node tools/gen-hosting-codes.mjs --write\n` +
    `// Verify:     node tools/gen-hosting-codes.mjs --check\n` +
    `\n` +
    `/** omx-clap-core's hosting codes, by key: every \`HOSTING_<DIMENSION>_CODES\` table, flattened. */\n` +
    `export const HOSTING_CODE = Object.freeze({\n` +
    lines.join('') +
    `} as const);\n`
  );
}

/** The generated module's text from the omx-clap-core modules in `dir`. */
export async function hostingCodesFileFrom(dir) {
  return hostingCodesFile(flattenHostingTables(await loadHostingTables(dir)));
}

function absent() {
  return (
    `omx-clap-core's TypeScript modules were not found in any of: ${clapCoreTsDirCandidates().join(', ')}. ` +
    'Install omx-clap-core (its modules in /usr/share/omx-clap-core/ts), set OMX_CLAP_CORE_TSDIR to its tsdir, or run make -C native deps.'
  );
}

async function main() {
  const mode = process.argv[2];
  if (!['--check', '--write', '--build'].includes(mode)) {
    console.error('usage: node tools/gen-hosting-codes.mjs --check|--write|--build');
    process.exit(2);
  }
  const dir = findClapCoreTsDir();
  if (dir === undefined) {
    if (mode === '--build') {
      console.log(`gen-hosting-codes: omx-clap-core not found, keeping the committed ${OUT}`);
      return;
    }
    console.error(`gen-hosting-codes: ${absent()}`);
    process.exit(2);
  }
  const content = await hostingCodesFileFrom(dir);
  let onDisk;
  try {
    onDisk = readFileSync(OUT, 'utf8');
  } catch {
    onDisk = undefined;
  }
  if (mode === '--check') {
    if (onDisk !== content) {
      console.error(`gen-hosting-codes: ${OUT} is stale against ${dir} — run with --write`);
      process.exit(1);
    }
    console.log('gen-hosting-codes: up to date');
    return;
  }
  if (onDisk !== content) writeFileSync(OUT, content);
  console.log(`gen-hosting-codes: ${onDisk === content ? 'up to date' : 'wrote'} ${OUT} from ${dir}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await main();
